"""Phase 6: build the listening set in audio/trimmed/ + trim_report.md.

Comparison clips are PLAIN (no prompt, no leak) — copied through unchanged,
exactly like the Phase 4/5 plain clips. The neufeld tone-tagged clips carry
the spoken style-prompt leak and are cut to the target sentence with the
Phase 3 whisper-timestamp method (find_cut/trim_wav from
experiments/tone/trim_clips.py — the Phase 4 pattern). Baseline tone clips
(no prompt) are copied through.

listen.html is generated by listen_page.py (imported below).

Usage:
    .venv/bin/python experiments/phase6/build_set.py
"""

import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
# Phase 3 helpers first: no trim_clips.py exists in this directory, so this
# unambiguously resolves to experiments/tone/trim_clips.py.
sys.path.insert(0, str(HERE.parent / "tone"))
from trim_clips import find_cut, trim_wav  # noqa: E402

sys.path.insert(0, str(HERE))
from listen_page import write_listen_page  # noqa: E402
from setup_plan import comparison_clips, tone_clips  # noqa: E402

RAW_DIR = HERE / "audio" / "raw"
TRIMMED_DIR = HERE / "audio" / "trimmed"


def main() -> None:
    import mlx_whisper  # lazy: keeps startup fast

    WHISPER_MODEL = "mlx-community/whisper-large-v3-turbo"
    rows = [
        "# Phase 6 — listening set build (audio/trimmed/)\n",
        "Comparison clips (plain) copied through untouched; the neufeld "
        "tone-tagged clips cut with the Phase 3 whisper-timestamp method.\n",
        "| Clip | Source | Cut at (s) | Match | Final (s) | Transcript |",
        "| --- | --- | ---: | ---: | ---: | --- |",
    ]
    TRIMMED_DIR.mkdir(parents=True, exist_ok=True)

    for name, text, category, phase5_name, voice in comparison_clips():
        src = RAW_DIR / f"{name}_000.wav"
        if not src.exists():
            print(f"{name}: raw clip missing, skipped", flush=True)
            continue
        out = TRIMMED_DIR / f"{name}.wav"
        shutil.copy2(src, out)
        print(f"{name}: copied (plain clip)", flush=True)
        rows.append(f"| {name} | plain copy | — | — | — | — |")

    for name, gen_text, sentence, tagged, key in tone_clips():
        src = RAW_DIR / f"{name}_000.wav"
        if not src.exists():
            print(f"{name}: raw clip missing, skipped", flush=True)
            continue
        if not tagged:
            out = TRIMMED_DIR / f"{name}.wav"
            shutil.copy2(src, out)
            print(f"{name}: copied (tone baseline)", flush=True)
            rows.append(f"| {name} | plain copy | — | — | — | — |")
            continue
        # Tagged tone clip: locate the target-sentence boundary and cut.
        result = mlx_whisper.transcribe(
            str(src), path_or_hf_repo=WHISPER_MODEL, word_timestamps=True
        )
        words = [w for seg in result["segments"] for w in seg.get("words", [])]
        if not words:
            print(f"{name}: no word timestamps, skipped", flush=True)
            continue
        cut, ratio = find_cut(words, sentence)
        out = TRIMMED_DIR / f"{name}_trim.wav"
        dur = trim_wav(src, cut, out)
        trimmed_text = mlx_whisper.transcribe(
            str(out), path_or_hf_repo=WHISPER_MODEL
        )["text"].strip()
        print(
            f"{out.stem:40s} cut {cut:5.2f}s  match {ratio:.2f}  -> {dur:4.1f}s"
            f"\n    transcript: {trimmed_text}\n",
            flush=True,
        )
        rows.append(
            f"| {out.stem} | `{gen_text}` | {cut:.2f} | {ratio:.2f} | "
            f"{dur:.1f} | {trimmed_text} |"
        )

    write_listen_page()
    (HERE / "trim_report.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
    print("wrote trim_report.md and listen.html")


if __name__ == "__main__":
    main()